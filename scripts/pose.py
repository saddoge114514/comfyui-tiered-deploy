def draw(pose, w, h, out):
    img = Image.new("RGB", (w, h), (0, 0, 0))
    d = ImageDraw.Draw(img)
    lw = max(4, int(min(w, h) * 0.012))
    r = max(4, int(min(w, h) * 0.010))
    for a, b in LIMBS:
        if a in pose and b in pose:
            d.line([pose[a], pose[b]], fill=COL.get(a, (255, 255, 255)), width=lw)
    for k, p in pose.items():
        d.ellipse([p[0] - r, p[1] - r, p[0] + r, p[1] + r], fill=COL.get(k, (255, 255, 255)))
    os.makedirs(os.path.dirname(out), exist_ok=True)
    img.save(out)
    print("wrote", out, img.size)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--pose", required=True, help="姿势名，或 @x,y;x,y;... 直接给 18 点")
    p.add_argument("--out", required=True)
    p.add_argument("--w", type=int, default=832)
    p.add_argument("--h", type=int, default=1216)
    a = p.parse_args()
    if a.pose.startswith("@"):
        pts = [tuple(int(v) for v in s.split(",")) for s in a.pose[1:].split(";")]
        pose = {i: pts[i] for i in range(len(pts))}
    else:
        pose = POSES[a.pose]
    draw(pose, a.w, a.h, a.out)


if __name__ == "__main__":
    main()
